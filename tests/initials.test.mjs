// ФИО с инициалами: фамилия рядом с инициалами не остаётся на виду, слово с заглавной слева от инициалов не крадёт метку.
// Данные выдуманы. Тот же набор в файле лежит в tests/control/podpisi-iniciali.txt
import test from 'node:test';
import assert from 'node:assert/strict';
import { loadMask } from './mask-api.mjs';

const api = loadMask();
const m = t => api.mask(t, []).masked;
// [текст, фамилия, которой не должно остаться, слово слева, которое остаётся]
const CASES = [
  ['Подписал И.С. Петров', 'Петров', 'Подписал'],
  ['Утвердил А.В. Сидоров.', 'Сидоров', 'Утвердил'],
  ['Согласовано: Н.П. Кузнецова', 'Кузнецова', 'Согласовано:'],
  ['Исполнитель И.И. Иванов, тел. 8 (495) 123-45-67', 'Иванов', 'Исполнитель'],
  ['Директор И.С. Петров', 'Петров', 'Директор'],
  ['Главный бухгалтер Е.А. Смирнова', 'Смирнова', 'Главный бухгалтер'],
  ['Генеральный директор ______ / И.С. Петров /', 'Петров', 'Генеральный директор'],
  ['И.С.Петров', 'Петров'],
  ['И. С. Петров', 'Петров'],
  ['Петров И.С.', 'Петров'],
  ['Петров И. С.', 'Петров'],
  ['письмо от И.С. Петрова', 'Петров', 'письмо от'],
  ['направить А.В. Сидоровой', 'Сидоров', 'направить'],
  ['И.С. Петров-Водкин', 'Водкин'],
  ['Должность\tФИО\nПодпись\tИ.С. Петров', 'Петров', 'Подпись\t'],
  ['Директор\tИ.С. Петров', 'Петров', 'Директор\t'],
  ['Ответственный\tЕ.А. Смирнова', 'Смирнова', 'Ответственный\t'],
];

for (const [text, sur, left] of CASES) {
  test(`инициалы: ${JSON.stringify(text)}`, () => {
    const out = m(text);
    assert.ok(!out.includes(sur), `фамилия осталась: ${out}`);
    assert.ok(!/[А-ЯЁ]\.\s?[А-ЯЁ]\./.test(out), `инициалы остались: ${out}`);
    if (left) assert.ok(out.includes(left), `слово слева спрятано: ${out}`);
  });
}

test('инициалы: оба порядка рядом дают два человека', () => {
  assert.equal(m('Петров И.С. и А.В. Сидоров'), '[ФИО_1] и [ФИО_2]');
  assert.equal(m('Петров И.С. Сидоров А.В.'), '[ФИО_1] [ФИО_2]');
});

test('инициалы: справа служебное слово или соседняя ячейка, метка остаётся у фамилии слева', () => {
  assert.equal(m('Петров И.С. Директор'), '[ФИО_1] Директор');
  assert.equal(m('Петров И.С.\tБухгалтер'), '[ФИО_1]\tБухгалтер');
});

test('инициалы: при неоднозначности прячется и слово слева, если оно похоже на фамилию', () => {
  assert.equal(m('Иванов И.И. Петров'), '[ФИО_1] [ФИО_2]');
  // ни одно слово не похоже на фамилию по форме: прячутся оба
  assert.ok(!m('Белых И.С. Подписал акт').includes('Белых'));
});
