// Маска с сейфом: одна сущность в разных документах и написаниях получает одну метку
import test from 'node:test';
import assert from 'node:assert/strict';
import { loadMask } from './mask-api.mjs';
import { safeNew, safeSetWords, safeRestore } from '../src/safe.mjs';

const api = loadMask();
// документы по очереди с одним сейфом, как это делает человек
function session(docs, safe = safeNew('тест'), opts = {}) {
  const out = [];
  for (const d of docs) { const r = api.mask(d, [], { ...opts, safe }); safe = r.safe; out.push(r); }
  return { out, safe };
}
const tagsOf = (r, value) => [...new Set(r.hits.filter(h => h.value === value).map(h => h.tag))];

test('без сейфа: метки русские, нумерация по типу с единицы', () => {
  const r = api.mask('ООО «Ромашка», ИНН 7729654321, директор Петров Иван Сергеевич, тел. +7 (916) 245-18-73, почта a@b.example', []);
  assert.equal(r.masked, '[ОРГ_1], ИНН [ИНН_1], директор [ФИО_1], тел. [ТЕЛ_1], почта [ПОЧТА_1]');
  assert.equal(r.safe.records.length, 5);
  assert.equal(r.added, 5);
});

test('организация: ООО «…», «… ООО», полная форма, без формы и в падежах получают одну метку, ИНН отдельно', () => {
  const { out, safe } = session([
    'Подрядчик: ООО «Каменный Мост», ИНН 7816135799.',
    'Акт подписали Каменный Мост ООО и заказчик.',
    'Общество с ограниченной ответственностью «Каменный Мост», именуемое в дальнейшем «Подрядчик».',
    'Письмо. Каменный Мост прислал счёт. Сотрудники Каменного Моста приехали, Каменному Мосту ответили, с Каменным Мостом согласовано.',
    'Сверка: ИНН 7816135799 по договору.',
  ]);
  for (const r of out) for (const h of r.hits.filter(h => h.t === 'ORG')) assert.equal(h.tag, '[ОРГ_1]', h.value);
  assert.equal(out[3].masked, 'Письмо. [ОРГ_1] прислал счёт. Сотрудники [ОРГ_1] приехали, [ОРГ_1] ответили, с [ОРГ_1] согласовано.');
  assert.deepEqual(tagsOf(out[4], '7816135799'), ['[ИНН_1]']);
  assert.deepEqual(safe.records.map(r => r.tag), ['[ОРГ_1]', '[ИНН_1]'], 'название и ИНН это разные метки');
  assert.ok(safe.records[0].forms.includes('Каменного Моста'));
});

test('организация без формы в первом документе не прячется: связывать не с чем', () => {
  const r = api.mask('Письмо. Каменный Мост прислал счёт.', [], { safe: safeNew() });
  assert.ok(!r.hits.some(h => h.t === 'ORG'));
});

test('человек: полное ФИО, родительный падеж, фамилия с инициалами и одна фамилия получают одну метку', () => {
  const { out, safe } = session([
    'Директор Петров Иван Сергеевич подписал договор.',
    'в лице директора Петрова Ивана Сергеевича, действующего на основании Устава',
    'Подпись: ______ / Петров И.С. /',
    'Передать документы Петрову до пятницы.',
  ]);
  for (const r of out) for (const h of r.hits.filter(h => h.t === 'PERSON')) assert.equal(h.tag, '[ФИО_1]', h.value);
  assert.equal(out[3].masked, 'Передать документы [ФИО_1] до пятницы.');
  assert.equal(safe.records.length, 1);
  assert.equal(safe.records[0].value, 'Петров Иван Сергеевич', 'для подстановки именительный падеж');
});

test('два человека с одной фамилией: одинокая фамилия не приписывается никому из них', () => {
  const { out } = session([
    'Петров Иван Сергеевич и Петрова Анна Ивановна подписали.',
    'Звонил Петровой вчера.',
  ]);
  assert.deepEqual(tagsOf(out[0], 'Петров Иван Сергеевич'), ['[ФИО_1]']);
  assert.deepEqual(tagsOf(out[0], 'Петрова Анна Ивановна'), ['[ФИО_2]']);
  assert.ok(!out[1].hits.some(h => h.tag === '[ФИО_1]' || h.tag === '[ФИО_2]'));
});

test('известное значение получает прежнюю метку, новое следующий свободный номер своего типа', () => {
  const { out } = session([
    'ООО «Альфа», ООО «Бета», ИНН 7729654321',
    'ООО «Гамма» и ООО «Бета», ИНН 7816135799 и ИНН 7729654321',
  ]);
  assert.equal(out[1].masked, '[ОРГ_3] и [ОРГ_2], ИНН [ИНН_2] и ИНН [ИНН_1]');
  assert.deepEqual(out[1].vault.map(v => [v.tag, v.fresh]), [['[ОРГ_3]', true], ['[ОРГ_2]', false], ['[ИНН_2]', true], ['[ИНН_1]', false]]);
  assert.equal(out[1].added, 2);
});

test('свои слова из сейфа ищутся в каждом новом документе', () => {
  const safe = safeSetWords(safeNew(), ['Северный поток-3', 'рецептура К-17']);
  const { out } = session(['Объект Северный поток-3 строится.', 'По рецептура К-17 и объекту северный поток-3 отчёт.'], safe);
  assert.equal(out[0].masked, 'Объект [СЛОВО_1] строится.');
  assert.equal(out[1].masked, 'По [СЛОВО_2] и объекту [СЛОВО_1] отчёт.');
});

test('написание из сейфа прячется и там, где правила его не находят', () => {
  const { out } = session(['Договор подряда № 41-КВ/2025 от 17.03.2025', 'Оплата по 41-КВ/2025 проведена.']);
  assert.equal(out[1].masked, 'Оплата по [ДОГОВОР_1] проведена.');
});

test('суммы из сейфа не ищутся в таблице с выключенным «прятать суммы»', () => {
  const { safe } = session(['Цена 4 896 000,00 руб.']);
  assert.equal(api.mask('Итого\t4 896 000,00', [], { safe, sums: false }).masked, 'Итого\t4 896 000,00');
  assert.equal(api.mask('Итого\t4 896 000,00', [], { safe }).masked, 'Итого\t[СУММА_1]');
});

test('сейфы двух клиентов не смешиваются', () => {
  const a = session(['ООО «Альфа», директор Петров Иван Сергеевич']).safe;
  const b = session(['ООО «Омега», директор Сидоров Павел Петрович']).safe;
  const ra = api.mask('ООО «Омега» и ООО «Альфа»', [], { safe: a }), rb = api.mask('ООО «Омега» и ООО «Альфа»', [], { safe: b });
  assert.equal(ra.masked, '[ОРГ_2] и [ОРГ_1]');
  assert.equal(rb.masked, '[ОРГ_1] и [ОРГ_2]');
  assert.equal(a.records.length, 2, 'исходный сейф не меняется: маска возвращает новый');
});

test('почта и адрес: разные значения с одинаковыми цифрами получают разные метки', () => {
  const r = api.mask('Почта ivan1@a.example и petr1@b.example, адреса: ул. Ленина, д. 20 и ул. Мира, д. 20. Ещё раз IVAN1@A.EXAMPLE', []);
  assert.equal(r.masked, 'Почта [ПОЧТА_1] и [ПОЧТА_2], адреса: [АДРЕС_1] и [АДРЕС_2]. Ещё раз [ПОЧТА_1]');
});

test('ответ нейросети возвращается по сейфу сессии', () => {
  const { safe } = session(['ООО «Каменный Мост», директор Петров Иван Сергеевич', 'Акт: Каменный Мост ООО, Петров И.С.']);
  assert.equal(safeRestore('Сверка: [орг_1] и [ФИО 1] согласны.', safe).text, 'Сверка: ООО «Каменный Мост» и Петров Иван Сергеевич согласны.');
});

test('фамилия на -ский в разных падежах одна, «Каменный Мост-Строй» не «Каменный Мост»', () => {
  const { out } = session([
    'Директор ООО «Каменный Мост» Мирский Олег Петрович.',
    'Письмо от Мирского Олега Петровича и Мирского О.П., звонил Мирскому. Каменный Мост-Строй тут ни при чём.',
  ]);
  assert.equal(out[1].masked, 'Письмо от [ФИО_1] и [ФИО_1], звонил [ФИО_1]. Каменный Мост-Строй тут ни при чём.');
});
